// Isolated UI/contract tests: requests are intercepted, never sent to a real account.
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const { installBrowserIdentity, user } = require('./browser-auth-fixture.cjs');
const base = process.env.TEST_BASE_URL || 'http://localhost:3100';
(async () => {
  const browser = await chromium.launch({headless:true,executablePath:'/usr/bin/google-chrome',args:['--no-sandbox']});
  const errors = [];
  const dir = 'output/auth-design'; fs.mkdirSync(dir,{recursive:true});
  const page = await browser.newPage({viewport:{width:1440,height:1000}});
  page.on('pageerror', e => errors.push(e.message));
  page.on('console', m => {if(m.type()==='error' && /hydrat/i.test(m.text())) errors.push(m.text());});
  page.setDefaultTimeout(15000);
  const calls = [];
  const cors = {'access-control-allow-origin':'*','access-control-allow-headers':'authorization,apikey,content-type,x-client-info,x-supabase-api-version','access-control-allow-methods':'GET,POST,PUT,OPTIONS'};
  let google = false, invitationExpired = false;
  await page.route('**/auth/v1/settings', r => r.fulfill({headers:cors,json:{external:{google}}}));
  await page.route('**/api/v1/access', r => r.fulfill({headers:cors,json:{status:'PENDING_APPROVAL',destination:'/access-pending'}}));
  await page.route('**/api/v1/auth/invitation', r => invitationExpired ? r.fulfill({headers:cors,status:410,json:{}}) : r.fulfill({headers:cors,json:{organization:{name:'Équipe QA'},role:'cashier'}}));
  await page.route('**/api/v1/auth/activate', r => {calls.push(['activate',r.request().postDataJSON()]);return r.fulfill({headers:cors,json:{message:'Invitation acceptée.'}});});
  await page.route('**/auth/v1/token?*', r => {calls.push(['login',r.request().postDataJSON()]);return r.fulfill({headers:cors,status:400,json:{code:'invalid_credentials',error_code:'invalid_credentials',msg:'Invalid login credentials'}});});
  await page.route('**/auth/v1/signup?*', r => {calls.push(['signup',r.request().postDataJSON()]);return r.fulfill({headers:cors,json:{...user,email_confirmed_at:null,identities:[{id:'qa'}]}});});
  await page.route('**/auth/v1/recover?*', async r => {calls.push(['recover',r.request().postDataJSON()]);await new Promise(resolve=>setTimeout(resolve,400));return r.fulfill({headers:cors,json:{}});});
  await page.route('**/auth/v1/resend?*', r => {calls.push(['resend',r.request().postDataJSON()]);return r.fulfill({headers:cors,json:{}});});
  await page.route('**/auth/v1/**',r=>r.request().method()==='OPTIONS'?r.fulfill({headers:cors,status:204,body:''}):r.fallback());
  await page.goto(base+'/login');
  await page.getByRole('heading',{name:'Accéder à VORTEX',exact:true}).waitFor();
  await page.waitForFunction(()=>!document.querySelector('button[type=submit],button:not([type])')?.disabled);
  await page.screenshot({caret:'initial',path:dir+'/login-desktop.png',fullPage:true});
  assert.equal(await page.getByRole('button',{name:/Continuer avec Google/}).count(),0);
  await page.getByRole('button',{name:'Se connecter par e-mail'}).click();
  await page.getByRole('alert').filter({hasText:'Vérifiez les champs'}).waitFor(); assert.equal(calls.length,0);
  await page.getByLabel('Adresse email',{exact:true}).fill('qa@example.test');
  await page.getByLabel('Mot de passe',{exact:true}).fill('private-password-123');
  await page.getByRole('button',{name:'Afficher le mot de passe'}).click();
  assert.equal(await page.locator('#auth-password').getAttribute('type'),'text');
  await page.getByRole('button',{name:'Se connecter par e-mail'}).click();
  await page.getByRole('alert').filter({hasText:'Email ou mot de passe incorrect.'}).waitFor().catch(async e=>{console.error('Login UI:',await page.locator('form').innerText(),'Calls:',calls);throw e;});
  google=true;await page.reload();await page.getByRole('button',{name:/Continuer avec Google/}).waitFor();await page.screenshot({caret:'initial',path:dir+'/login-desktop-google.png',fullPage:true});
  await page.goto(base+'/signup');
  await page.getByLabel('Votre nom',{exact:true}).fill('Propriétaire QA');
  await page.getByLabel('Adresse email',{exact:true}).fill('qa@example.test');
  await page.getByLabel('Mot de passe',{exact:true}).fill('Valid-password-123');
  await page.getByRole('button',{name:'Continuer',exact:true}).click();
  await page.getByLabel('Nom commercial').fill('Entreprise QA');
  await page.getByLabel('Fuseau horaire').fill('bad/timezone');
  await page.getByRole('button',{name:'Continuer',exact:true}).click();
  await page.getByText('Indiquez un fuseau valide',{exact:false}).waitFor();
  await page.getByLabel('Fuseau horaire').fill('Africa/Porto-Novo');
  await page.getByRole('button',{name:'Retour',exact:true}).click();
  assert.equal(await page.getByLabel('Votre nom',{exact:true}).inputValue(),'Propriétaire QA');
  await page.getByRole('button',{name:'Continuer',exact:true}).click();
  await page.getByRole('button',{name:'Continuer',exact:true}).click();
  await page.getByLabel('Nom du point de vente').fill('Boutique QA');
  await page.getByLabel('Ville / adresse').fill('Cotonou');
  await page.getByRole('button',{name:'Continuer',exact:true}).click();
  await page.screenshot({caret:'initial',path:dir+'/signup-recap.png',fullPage:true});
  await page.getByRole('button',{name:'Envoyer ma demande'}).click();
  await page.waitForURL('**/verify-email');
  const signup=calls.find(c=>c[0]==='signup')[1];assert.equal(signup.data.vortex_access_request,true);assert.equal(signup.data.vortex_onboarding.payload.storeName,'Boutique QA');assert.equal(signup.data.vortex_onboarding.payload.password,undefined);
  await page.getByLabel('Adresse email',{exact:true}).fill('qa@example.test');
  await page.getByRole('button',{name:'Renvoyer le lien'}).click();
  await page.getByRole('status').filter({hasText:'nouveau lien'}).waitFor();
  await page.goto(base+'/forgot-password');await page.getByLabel('Adresse email',{exact:true}).fill('qa@example.test');
  await page.getByRole('button',{name:'Envoyer le lien'}).click();
  assert.ok(await page.getByRole('button',{name:'Veuillez patienter…'}).isDisabled());
  await page.getByRole('status').filter({hasText:'Si ce compte existe'}).waitFor();
  await page.goto(base+'/reset-password?error=invalid_link');await page.getByRole('alert').filter({hasText:'Lien invalide'}).waitFor();assert.equal(await page.locator('#auth-password').count(),0);
  await page.goto(base+'/invite/activate');await page.getByRole('alert').filter({hasText:'incomplet'}).waitFor();assert.ok(await page.getByRole('button',{name:'Activer mon compte'}).isDisabled());
  invitationExpired=true;await page.goto(base+'/invite/activate?token=expired');await page.getByRole('alert').filter({hasText:'expirée'}).waitFor();
  invitationExpired=false;await page.goto(base+'/invite/activate?token=qa');await page.getByText('Équipe QA',{exact:true}).waitFor();
  await page.screenshot({caret:'initial',path:dir+'/invite.png',fullPage:true});
  await installBrowserIdentity(page,base);
  await page.goto(base+'/reset-password');
  await page.route('**/auth/v1/user',r=>r.request().method()==='PUT' ? (calls.push(['reset',r.request().postDataJSON()]),r.fulfill({headers:cors,json:user})) : r.fulfill({headers:cors,json:user}));
  await page.route('**/auth/v1/logout?*',r=>r.fulfill({headers:cors,json:{}}));
  await page.getByLabel('Nouveau mot de passe',{exact:true}).fill('Updated-password-123');
  await page.getByLabel('Confirmer le mot de passe',{exact:true}).fill('different-password');
  await page.getByRole('button',{name:'Enregistrer le mot de passe'}).click();await page.getByText('Les mots de passe ne correspondent pas.').waitFor();
  await page.getByLabel('Confirmer le mot de passe',{exact:true}).fill('Updated-password-123');
  await page.getByRole('button',{name:'Enregistrer le mot de passe'}).click();await page.getByRole('status').filter({hasText:'Mot de passe enregistré'}).waitFor().catch(async e=>{console.error('Reset UI:',await page.locator('main').innerText(),'Calls:',calls.map(c=>c[0]));throw e;});
  assert.equal(calls.find(c=>c[0]==='reset')[1].password,'Updated-password-123');
  await installBrowserIdentity(page,base);await page.goto(base+'/verify-email');await page.getByRole('status').filter({hasText:'Adresse email confirmée'}).waitFor();
  await page.goto(base+'/invite/activate?token=qa');await page.getByRole('button',{name:'Activer mon compte'}).click();await page.waitForURL('**/access-pending');assert.equal(calls.find(c=>c[0]==='activate')[1].token,'qa');
  await page.context().clearCookies();
  for(const width of [360,390,768,1024,1440]){
    await page.setViewportSize({width,height:900});
    for(const path of ['/login','/signup','/forgot-password','/reset-password','/verify-email','/invite/activate?token=qa']){
      await page.goto(base+path);await page.getByRole('heading',{level:1}).waitFor();
      assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),`${path} overflows at ${width}`);
      if(width===390)await page.screenshot({caret:'initial',path:`${dir}/${path.split('?')[0].replaceAll('/','')}-mobile.png`,fullPage:true});
    }
  }
  assert.deepEqual(errors,[],'No browser exceptions');
  console.log('Auth design QA passed: six routes, 5 viewports, form validation, loading/error states, signup draft, provider discovery, resend/recovery, password update, invitation acceptance. All Auth calls use isolated fixtures.');
  await browser.close();
})().catch(e=>{console.error(e);process.exit(1);});
